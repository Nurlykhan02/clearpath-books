export function generateStaticParams() {
  return Object.keys(posts).map((slug) => ({ slug }));
}

export default async function BlogPostPage({
  params,
}: PageProps<"/blog/[slug]">) {
  const { slug } = await params;
  const post = posts[slug];

  if (!post) notFound();

  return (
    <section className="section" lang="ru">
      <div className="wrap" style={{ maxWidth: "720px" }}>
        <Reveal>
          <Link
            href="/blog"
            style={{ color: "var(--clay-deep)", fontWeight: 600, fontSize: "0.92rem" }}
          >
            ← Назад к блогу
          </Link>
          <time
            dateTime={post.dateTime}
            style={{
              display: "block",
              marginTop: "1.5rem",
              fontSize: "0.85rem",
              color: "var(--ink-faint)",
            }}
          >
            {post.date}
          </time>
          <h1 className="heading h-l" style={{ marginTop: "0.75rem" }}>
            {post.title}
          </h1>
        </Reveal>

        <div style={{ marginTop: "2rem" }}>
          {post.content.map((paragraph, i) => (
            <Reveal key={i} delay={i * 0.05}>
              <p
                style={{
                  fontSize: "1.1rem",
                  lineHeight: 1.7,
                  color: "var(--ink-soft)",
                  marginBottom: "1.25rem",
                }}
              >
                {paragraph}
              </p>
            </Reveal>
          ))}
        </div>
      </div>
    </section>
  );
}
